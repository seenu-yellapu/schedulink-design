// The token build (ADR 0008). Reads tokens/*.tokens.json, generates the brand ramp, resolves aliases, and writes:
//   tokens/palette.tokens.json   the generated brand ramp
//   tokens/build/globals.css     every token as a CSS custom property, plus a class per text style
//   tokens/build/tokens.json     the same values in the Claude design system format, for re-syncing the artifact
//   tokens/build/contrast.json   every checked pair and its ratio
//   docs/03-color.md             the tables between the generated markers
//   specimen/index.html          the specimen page
// Then it checks contrast and house style, and fails on any failure.
// node scripts/tokens.mjs          write everything
// node scripts/tokens.mjs --check  write nothing; fail if any output differs from what is on disk (CI)
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { brandRamp, TARGETS } from './brand-ramp.mjs';
import { contrast, hexToOklch, fmtOklch } from './color.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const readJson = (p) => JSON.parse(read(p));
const errors = [];
const outputs = new Map();
const emit = (p, text) => outputs.set(p, text.endsWith('\n') ? text : text + '\n');

// 1. Inputs
const brandInput = readJson('tokens/brand.tokens.json').brand.input.$value;
const semantic = readJson('tokens/semantic.tokens.json').color;
const typography = readJson('tokens/typography.tokens.json');
const dimension = readJson('tokens/dimension.tokens.json');
const shadow = readJson('tokens/shadow.tokens.json').shadow;

// 2. The brand ramp
const ramp = brandRamp(brandInput);
if (ramp.nudged) errors.push(`brand input ${brandInput} fails white text at ${TARGETS.onSolid}:1 and was darkened; change the input or the target`);
if (ramp.steps[8] !== brandInput.toUpperCase()) errors.push(`step 9 (${ramp.steps[8]}) is not the brand input (${brandInput})`);
const STEP_ROLE = ['App background', 'Subtle background', 'Element tint', 'Hovered tint', 'Selected tint', 'Subtle border', 'Border', 'Strong border', 'Solid', 'Pressed solid', 'Brand text', 'Darkest'];
const palette = {
  $description: `GENERATED by scripts/tokens.mjs from tokens/brand.tokens.json (${brandInput}). Do not edit.`,
  palette: { brand: Object.fromEntries(ramp.steps.map((hex, i) => [String(i + 1), { $type: 'color', $value: hex, $description: STEP_ROLE[i] }])) },
};
emit('tokens/palette.tokens.json', JSON.stringify(palette, null, 2));

// 3. Resolve color roles
const resolve = (v, seen = []) => {
  const m = /^\{palette\.brand\.(\d+)\}$/.exec(v);
  if (!m) return v;
  const hex = ramp.steps[Number(m[1]) - 1];
  if (!hex) throw new Error(`unknown alias ${v}`);
  return hex;
};
const colors = Object.fromEntries(Object.entries(semantic).map(([name, t]) => [name, {
  value: resolve(t.$value), alias: t.$value.startsWith('{') ? t.$value.slice(1, -1) : null,
  was: t.$extensions?.schedulink?.was ?? null, usage: t.$description,
}]));
for (const [n, c] of Object.entries(colors)) if (!/^#[0-9A-F]{6}$/.test(c.value)) errors.push(`color ${n}: ${c.value} is not #RRGGBB`);

// 4. globals.css
// The named face (first) and any name with a space are quoted; fallbacks like Helvetica and generic keywords are not.
const fam = (v) => v.map((f, i) => (i === 0 || /\s/.test(f) ? `"${f}"` : f)).join(', ');
const css = [
  '/* GENERATED by scripts/tokens.mjs from tokens/. Do not edit; change the token files and rebuild. */',
  ':root {',
  ...Object.entries(colors).map(([n, c]) => `  --${n}: ${c.value};`),
  ...ramp.steps.map((h, i) => `  --brand-${i + 1}: ${h};`),
  ...Object.entries(typography.font).map(([n, f]) => `  --font-${n}: ${fam(f.$value)};`),
  ...Object.entries(dimension.space).map(([n, t]) => `  --${n}: ${t.$value};`),
  ...Object.entries(dimension.radius).map(([n, t]) => `  --${n}: ${t.$value};`),
  ...Object.entries(shadow).map(([n, t]) => `  --${n}: ${t.$value};`),
  '}',
  ...Object.entries(typography.style).map(([n, t]) => {
    const v = t.$value; const fname = /\{font\.(\w+)\}/.exec(v.fontFamily)[1];
    const tt = t.$extensions?.schedulink?.textTransform;
    return `.type-${n} { font-family: var(--font-${fname}); font-size: ${v.fontSize}; line-height: ${v.lineHeight}; font-weight: ${v.fontWeight};${v.letterSpacing ? ` letter-spacing: ${v.letterSpacing};` : ''}${tt ? ` text-transform: ${tt};` : ''} }`;
  }),
].join('\n');
emit('tokens/build/globals.css', css);

// 5. The Claude design system format (a list per family), so the ScheduLink Marketing artifact can be re-synced
const dsTokens = {
  name: 'ScheduLink Marketing', version: 1,
  meta: { source: 'GENERATED from github.com/seenu-yellapu/schedulink-design by scripts/tokens.mjs. Edit the repo, not this file.' },
  color: { themes: [{ id: 'light', name: 'Light' }], tokens: Object.entries(colors).map(([name, c]) => ({ name, value: c.value, usage: c.usage })) },
  type: {
    fonts: [],
    families: Object.fromEntries(Object.entries(typography.font).map(([n, f]) => [n, fam(f.$value)])),
    groups: [...new Set(Object.values(typography.style).map((t) => t.$extensions.schedulink.group))].map((g) => ({
      name: g, family: /\{font\.(\w+)\}/.exec(Object.values(typography.style).find((t) => t.$extensions.schedulink.group === g).$value.fontFamily)[1],
      styles: Object.entries(typography.style).filter(([, t]) => t.$extensions.schedulink.group === g).map(([name, t]) => ({
        name, fontSize: t.$value.fontSize, lineHeight: t.$value.lineHeight, fontWeight: t.$value.fontWeight,
        ...(t.$value.letterSpacing ? { letterSpacing: t.$value.letterSpacing } : {}),
        ...(t.$extensions.schedulink.textTransform ? { textTransform: t.$extensions.schedulink.textTransform } : {}),
      })),
    })),
  },
  spacing: { tokens: Object.entries(dimension.space).map(([name, t]) => ({ name, value: t.$value, usage: t.$description })) },
  radius: { tokens: Object.entries(dimension.radius).map(([name, t]) => ({ name, value: t.$value, usage: t.$description })) },
  shadow: { tokens: Object.entries(shadow).map(([name, t]) => ({ name, value: t.$value, usage: t.$description })) },
};
emit('tokens/build/tokens.json', JSON.stringify(dsTokens, null, 2));

// 6. Contrast (ADR 0007). [foreground, ground, minimum, why]
const PAIRS = [
  ['ink', 'surface', 4.5, 'headlines and text'], ['ink', 'page-grey', 4.5, 'text in sections on the grey'],
  ['ink', 'surface-sunken', 4.5, 'text on sunken bands'], ['ink', 'attention', 4.5, 'attention panels'],
  ['ink-secondary', 'surface', 4.5, 'body copy'], ['ink-secondary', 'page-grey', 4.5, 'body copy on the grey'],
  ['ink-secondary', 'surface-sunken', 4.5, 'body copy on sunken bands'],
  ['ink-muted', 'surface', 4.5, 'eyebrows, captions'], ['ink-muted', 'surface-sunken', 4.5, 'captions on sunken bands'],
  ['ink-muted', 'page-grey', 4.5, 'captions in sections on the grey'],
  ['brand', 'surface', 4.5, 'section tags and the selected tab (12px text)'], ['brand', 'page-grey', 4.5, 'section tags on the grey'],
  ['on-brand', 'brand', TARGETS.onSolid, 'primary button label'], ['on-brand', 'brand-strong', 4.5, 'primary button label on hover'],
  ['brand-strong', 'surface', TARGETS.text, 'links'], ['brand-strong', 'page-grey', TARGETS.text, 'links on the grey'],
  ['brand-strong', 'brand-soft', TARGETS.text, 'text on the brand tint'],
  ['status-overdue-text', 'status-overdue-bg', 4.5, 'overdue pill'], ['status-today-text', 'status-today-bg', 4.5, 'due-today pill'],
  ['status-later-text', 'status-later-bg', 4.5, 'due-later pill'], ['on-brand', 'surface-invert', 4.5, 'footer text'],
  ['line-strong', 'surface', 3, 'control borders and focus rings'], ['confirm', 'surface', 3, 'tick badge as a shape'],
  ['on-brand', 'confirm', 3, 'white tick on the green badge'],
];
// A failing pair kept from the source system is listed here with its reason; it is reported, not fixed silently.
const KNOWN = {
  'ink-muted/page-grey': 'Carried over from ScheduLink Marketing: captions in grey sections. Calls for Seenu: darken ink-muted or keep captions off the grey.',
  'ink-muted/surface-sunken': 'Carried over from ScheduLink Marketing: captions on sunken bands. Same call as ink-muted/page-grey.',
};
const report = PAIRS.map(([fg, bg, min, why]) => {
  const ratio = +contrast(colors[fg].value, colors[bg].value).toFixed(2);
  const key = `${fg}/${bg}`;
  return { fg, bg, min, ratio, pass: ratio >= min, known: !!KNOWN[key], why, note: KNOWN[key] ?? null };
});
for (const r of report) if (!r.pass && !r.known) errors.push(`contrast ${r.fg} on ${r.bg}: ${r.ratio}:1, needs ${r.min}:1 (${r.why})`);
for (const k of Object.keys(KNOWN)) {
  const r = report.find((x) => `${x.fg}/${x.bg}` === k);
  if (r?.pass) errors.push(`${k} now passes (${r.ratio}:1); remove it from KNOWN in scripts/tokens.mjs`);
}
emit('tokens/build/contrast.json', JSON.stringify({ total: report.length, failed: report.filter((r) => !r.pass && !r.known).length, known: report.filter((r) => r.known).length, pairs: report }, null, 2));

// 7. Generated tables in docs/03-color.md
const swatch = (h) => `\`${h}\``;
const rampTable = ['| Step | Role | Value | OKLCH |', '|---|---|---|---|',
  ...ramp.steps.map((h, i) => `| ${i + 1} | ${STEP_ROLE[i]} | ${swatch(h)} | ${fmtOklch(hexToOklch(h))} |`)].join('\n');
const rolesTable = ['| Role | Value | Source | Use |', '|---|---|---|---|',
  ...Object.entries(colors).map(([n, c]) => `| \`${n}\` | ${swatch(c.value)} | ${c.alias ? `${c.alias.replace('palette.', '')}${c.was && c.was !== c.value ? ` (was ${swatch(c.was)})` : ''}` : 'set by hand'} | ${c.usage.replace(/\|/g, '/')} |`)].join('\n');
const contrastTable = ['| Text or shape | On | Ratio | Needs | Result |', '|---|---|---|---|---|',
  ...report.map((r) => `| \`${r.fg}\` | \`${r.bg}\` | ${r.ratio.toFixed(2)}:1 | ${r.min}:1 | ${r.pass ? 'Pass' : r.known ? 'Known failure, see below' : 'FAIL'} |`)].join('\n');
const knownList = Object.entries(KNOWN).map(([k, v]) => `- \`${k}\`: ${v}`).join('\n');
const colorDoc = read('docs/03-color.md');
const gen = (doc, name, body) => {
  const re = new RegExp(`(<!-- generated:${name}:begin -->)[\\s\\S]*?(<!-- generated:${name}:end -->)`);
  if (!re.test(doc)) { errors.push(`docs/03-color.md is missing the generated:${name} markers`); return doc; }
  return doc.replace(re, `$1\n${body}\n$2`);
};
let doc = gen(colorDoc, 'ramp', rampTable);
doc = gen(doc, 'roles', rolesTable);
doc = gen(doc, 'contrast', `${contrastTable}\n\n${knownList}`);
emit('docs/03-color.md', doc);

// 8. House style: no em dashes in anything a person reads (docs/11-content.md)
const prose = ['README.md', 'CLAUDE.md', 'AGENTS.md',
  ...readdirSync(join(ROOT, 'docs')).filter((f) => f.endsWith('.md')).map((f) => `docs/${f}`),
  ...readdirSync(join(ROOT, 'docs/adr')).filter((f) => f.endsWith('.md')).map((f) => `docs/adr/${f}`),
  ...readdirSync(join(ROOT, 'components')).filter((d) => existsSync(join(ROOT, 'components', d, 'README.md'))).map((d) => `components/${d}/README.md`)];
for (const p of prose) {
  const text = outputs.get(p) ?? read(p);
  text.split('\n').forEach((line, i) => { if (line.includes('—')) errors.push(`${p}:${i + 1} has an em dash`); });
}

// 9. The specimen
const { buildSpecimen } = await import('./specimen.mjs');
emit('specimen/index.html', buildSpecimen({ ROOT, colors, ramp, STEP_ROLE, typography, dimension, shadow, report, css }));

// 10. Write or compare
let drift = 0;
for (const [p, text] of outputs) {
  const abs = join(ROOT, p);
  const now = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
  if (now === text) continue;
  if (CHECK) { drift++; errors.push(`${p} is out of date; run node scripts/tokens.mjs and commit the result`); }
  else { mkdirSync(dirname(abs), { recursive: true }); writeFileSync(abs, text); console.log(`wrote ${p}`); }
}
const passed = report.filter((r) => r.pass).length;
console.log(`brand ${brandInput} -> 12 steps; ${Object.keys(colors).length} color roles; contrast ${passed}/${report.length} pass, ${report.filter((r) => r.known).length} known failures`);
if (errors.length) { console.error(errors.map((e) => `error: ${e}`).join('\n')); process.exit(1); }
